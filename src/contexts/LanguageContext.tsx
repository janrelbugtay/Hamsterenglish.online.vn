const STORAGE_LANG_KEY = "hamster_app_language_v1";
const STORAGE_TRANSLATE_ALL_KEY = "hamster_translate_all_v1";
const STORAGE_KEEP_ESL_KEY = "hamster_keep_esl_prompts_v1";

interface LanguageContextValue {
  language: AppLanguageCode;
  currentLanguageOption: LanguageOption;
  setLanguage: (code: AppLanguageCode) => void;
  detectBrowserLanguage: () => AppLanguageCode;
  t: (key: string, fallback?: string) => string;
  translateAllScreens: boolean;
  setTranslateAllScreens: (val: boolean) => void;
  keepQuizPromptsEnglish: boolean;
  setKeepQuizPromptsEnglish: (val: boolean) => void;
}

const LanguageContext = createContext<LanguageContextValue | null>(null);

function resolveInitialLanguage(): AppLanguageCode {
  if (typeof window === "undefined") return "en";
  try {
    const saved = localStorage.getItem(STORAGE_LANG_KEY);
    if (saved && LANGUAGE_OPTIONS.some((l) => l.code === saved)) {
      return saved as AppLanguageCode;
    }
  } catch {}
  return "en";
}

function detectLocaleCode(): AppLanguageCode {
  if (typeof navigator === "undefined") return "en";
  const langs = [navigator.language, ...(navigator.languages || [])].filter(Boolean);
  for (const raw of langs) {
    const base = raw.toLowerCase().split("-")[0];
    if (base === "fil") return "tl";
    const match = LANGUAGE_OPTIONS.find((l) => l.code === base);
    if (match) return match.code;
  }
  return "en";
}

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguageCode>(resolveInitialLanguage);
  const [translateAllScreens, setTranslateAllScreensState] = useState<boolean>(() => {
    if (typeof window === "undefined") return true;
    try {
      const saved = localStorage.getItem(STORAGE_TRANSLATE_ALL_KEY);
      return saved === null ? true : saved === "true";
    } catch {
      return true;
    }
  });
  const [keepQuizPromptsEnglish, setKeepQuizPromptsEnglishState] = useState<boolean>(() => {
    if (typeof window === "undefined") return true;
    try {
      const saved = localStorage.getItem(STORAGE_KEEP_ESL_KEY);
      return saved === null ? true : saved === "true";
    } catch {
      return true;
    }
  });

  const currentLanguageOption = useMemo(
    () => LANGUAGE_OPTIONS.find((l) => l.code === language) || LANGUAGE_OPTIONS[0],
    [language]
  );

  const setLanguage = (code: AppLanguageCode) => {
    setLanguageState(code);
    try {
      localStorage.setItem(STORAGE_LANG_KEY, code);
    } catch {}
  };

  const setTranslateAllScreens = (val: boolean) => {
    setTranslateAllScreensState(val);
    try {
      localStorage.setItem(STORAGE_TRANSLATE_ALL_KEY, String(val));
    } catch {}
  };

  const setKeepQuizPromptsEnglish = (val: boolean) => {
    setKeepQuizPromptsEnglishState(val);
    try {
      localStorage.setItem(STORAGE_KEEP_ESL_KEY, String(val));
    } catch {}
  };

  const detectBrowserLanguage = () => {
    const detected = detectLocaleCode();
    setLanguage(detected);
    return detected;
  };

  useLayoutEffect(() => {
    if (typeof document === "undefined") return;
    document.documentElement.lang = language;
    document.documentElement.dir = currentLanguageOption.dir;
  }, [language, currentLanguageOption.dir]);

  // Safe Cross-App Phrasebook + Dynamic Pattern DOM Bridge for sub-views & games
  useEffect(() => {
    if (typeof document === "undefined") return;
    const originalTextMap = new WeakMap<Text, string>();
    const lastTranslatedMap = new WeakMap<Text, string>();
    const originalPlaceholderMap = new WeakMap<HTMLInputElement | HTMLTextAreaElement, string>();
    const lastPlaceholderTranslatedMap = new WeakMap<HTMLInputElement | HTMLTextAreaElement, string>();
    const touchedTexts = new Set<Text>();
    const touchedInputs = new Set<HTMLInputElement | HTMLTextAreaElement>();

    const phraseLookup = new Map<string, string>();
    if (language !== "en" && translateAllScreens) {
      for (const [eng, map] of Object.entries(COMMON_UI_PHRASES)) {
        const localized = map[language];
        if (localized) {
          phraseLookup.set(eng.trim().toLowerCase(), localized);
        }
      }
    }

    const lookupExactOrDynamic = (text: string): string | null => {
      const exact = phraseLookup.get(text.toLowerCase());
      if (exact) return exact;
      for (const rule of DYNAMIC_PATTERNS) {
        const m = text.match(rule.match);
        if (m) {
          return rule.format(m, language);
        }
      }
      return null;
    };

    const translateText = (source: string): string | null => {
      const clean = source.trim();
      if (!clean || clean.length < 2 || clean.length > 120) return null;

      const direct = lookupExactOrDynamic(clean);
      if (direct) return direct;

      // Also match buttons/badges that wrap a UI phrase with decorative emojis/symbols (e.g. "Play Again 🔄", "⚙️ Settings")
      const stripped = clean.match(/^([^\p{L}\p{N}+]+)([\p{L}\p{N}].*?[\p{L}\p{N})!?.])$|^([\p{L}\p{N}].*?[\p{L}\p{N})!?.])([^\p{L}\p{N}]+)$/u);
      if (stripped) {
        const leadSym = stripped[1] || "";
        const core = (stripped[2] || stripped[3] || "").trim();
        const trailSym = stripped[4] || "";
        if (core.length >= 2) {
          const coreTrans = lookupExactOrDynamic(core);
          if (coreTrans) {
            return `${leadSym}${coreTrans}${trailSym}`;
          }
        }
      }

      return null;
    };

    const shouldSkipElement = (el: Element | null): boolean => {
      if (!el) return true;
      // Unconditionally protect marked non-translatable regions and ALL game topics
      if (
        el.closest(
          "[data-no-translate], [data-game-topic], code, pre, script, style, svg, .font-mono"
        )
      ) {
        return true;
      }
      if (keepQuizPromptsEnglish && el.closest("[data-quiz-question], [data-esl-prompt]")) {
        return true;
      }
      return false;
    };

    const applyToTextNode = (node: Text) => {
      const parent = node.parentElement;
      if (!parent || shouldSkipElement(parent)) return;
      const raw = node.nodeValue || "";
      const trimmed = raw.trim();
      if (!trimmed) return;

      // If React externally changed this node's text since our last write, treat it as a fresh source string
      const lastWritten = lastTranslatedMap.get(node);
      if (lastWritten === undefined || trimmed !== lastWritten) {
        originalTextMap.set(node, trimmed);
      }

      const orig = originalTextMap.get(node) ?? trimmed;
      const translated = translateText(orig);
      if (translated && trimmed !== translated) {
        const idx = raw.indexOf(trimmed);
        const lead = idx >= 0 ? raw.slice(0, idx) : "";
        const trail = idx >= 0 ? raw.slice(idx + trimmed.length) : "";
        lastTranslatedMap.set(node, translated);
        node.nodeValue = `${lead}${translated}${trail}`;
        touchedTexts.add(node);
      }
    };

    const applyToNodeTree = (root: Node) => {
      if (language === "en" || !translateAllScreens) return;

      if (root.nodeType === Node.TEXT_NODE) {
        applyToTextNode(root as Text);
        return;
      }

      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node = walker.nextNode() as Text | null;
      while (node) {
        applyToTextNode(node);
        node = walker.nextNode() as Text | null;
      }

      if (root instanceof Element) {
        const inputs = root.querySelectorAll("input[placeholder], textarea[placeholder]");
        inputs.forEach((el) => {
          const inp = el as HTMLInputElement | HTMLTextAreaElement;
          if (shouldSkipElement(inp)) return;
          const ph = inp.placeholder?.trim();
          if (!ph) return;
          const lastPh = lastPlaceholderTranslatedMap.get(inp);
          if (lastPh === undefined || ph !== lastPh) {
            originalPlaceholderMap.set(inp, ph);
          }
          const orig = originalPlaceholderMap.get(inp) ?? ph;
          const translated = translateText(orig);
          if (translated && ph !== translated) {
            lastPlaceholderTranslatedMap.set(inp, translated);
            inp.placeholder = translated;
            touchedInputs.add(inp);
          }
        });
      }
    };

    if (language !== "en" && translateAllScreens) {
      applyToNodeTree(document.body);
    }

    let rafPending = false;
    const pendingNodes = new Set<Node>();
    const observer =
      language !== "en" && translateAllScreens
        ? new MutationObserver((mutations) => {
            for (const m of mutations) {
              if (m.type === "childList") {
                m.addedNodes.forEach((n) => pendingNodes.add(n));
              } else if (m.type === "characterData" && m.target) {
                pendingNodes.add(m.target);
              }
            }
            if (!rafPending && pendingNodes.size > 0) {
              rafPending = true;
              requestAnimationFrame(() => {
                rafPending = false;
                pendingNodes.forEach((n) => applyToNodeTree(n));
                pendingNodes.clear();
              });
            }
          })
        : null;

    if (observer) {
      observer.observe(document.body, {
        childList: true,
        subtree: true,
        characterData: true,
      });
    }

    return () => {
      if (observer) observer.disconnect();
      touchedTexts.forEach((txt) => {
        const orig = originalTextMap.get(txt);
        const lastWritten = lastTranslatedMap.get(txt);
        if (orig && txt.isConnected && txt.nodeValue?.trim() === lastWritten) {
          txt.nodeValue = orig;
        }
      });
      touchedInputs.forEach((inp) => {
        const orig = originalPlaceholderMap.get(inp);
        const lastWritten = lastPlaceholderTranslatedMap.get(inp);
        if (orig && inp.isConnected && inp.placeholder?.trim() === lastWritten) {
          inp.placeholder = orig;
        }
      });
    };
  }, [language, translateAllScreens, keepQuizPromptsEnglish]);

  const t = useMemo(() => {
    const dict = TRANSLATIONS[language] || EN_DICT;
    return (key: string, fallback?: string) => dict[key] ?? EN_DICT[key] ?? fallback ?? key;
  }, [language]);

  const value: LanguageContextValue = {
    language,
    currentLanguageOption,
    setLanguage,
    detectBrowserLanguage,
    t,
    translateAllScreens,
    setTranslateAllScreens,
    keepQuizPromptsEnglish,
    setKeepQuizPromptsEnglish,
  };

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      language: "en",
      currentLanguageOption: LANGUAGE_OPTIONS[0],
      setLanguage: () => {},
      detectBrowserLanguage: () => "en",
      t: (key: string, fallback?: string) => EN_DICT[key] ?? fallback ?? key,
      translateAllScreens: true,
      setTranslateAllScreens: () => {},
      keepQuizPromptsEnglish: true,
      setKeepQuizPromptsEnglish: () => {},
    };
  }
  return ctx;
}
